// Pre-build / pre-serve: generate src/environments/*.ts from .env.
// Usage: node scripts/set-env.mjs [--production]
// With --production, placeholder or missing values are reported; they fail the
// build when CI=true or NYX_STRICT=true (so a real deploy can't ship them).
import { mkdirSync, writeFileSync } from 'node:fs';
import { loadConfig, productionProblems } from './env.mjs';

const c = loadConfig();
const isProd = process.argv.includes('--production');

const file = (production, siteUrl) => `// AUTO-GENERATED by scripts/set-env.mjs from .env — do not edit or commit.
// Public, non-secret configuration only (CLAUDE.md §7).
export const environment = ${JSON.stringify(
  {
    production,
    siteUrl,
    tourEndpoint: c.tourEndpoint,
    turnstileSiteKey: c.turnstileSiteKey,
    cfAnalyticsToken: c.cfAnalyticsToken,
    contact: c.contact,
  },
  null,
  2,
)};
`;

mkdirSync('src/environments', { recursive: true });
writeFileSync('src/environments/environment.ts', file(true, c.siteUrl));
writeFileSync('src/environments/environment.development.ts', file(false, 'http://localhost:4200'));
console.log('[env] src/environments generated from', process.env.NYX_SITE_URL ? 'environment' : 'defaults');

if (isProd) {
  const problems = productionProblems(c);
  if (problems.length) {
    const strict = process.env.CI === 'true' || process.env.NYX_STRICT === 'true';
    const tag = strict ? '[env] ERROR' : '[env] WARNING';
    for (const p of problems) console[strict ? 'error' : 'warn'](`${tag}: ${p}`);
    if (strict) {
      console.error('[env] Fix these in .env (or the host\'s environment variables) before deploying.');
      process.exit(1);
    }
    console.warn('[env] Not production-ready. Set NYX_STRICT=true to make this fail the build.');
  }
}
